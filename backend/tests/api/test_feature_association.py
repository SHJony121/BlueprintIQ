def test_the_arrow_can_be_part_of_the_leaders_own_polyline(api: TestClient) -> None:
    # Start -> far end -> arrow wing -> wing -> far end, drawn as one connected path.
    far = (225.0, 300.0)
    wing1, wing2 = (235.0, 297.5), (235.0, 302.5)
    fused = Shape("polyline", (265.0, 300.0, *far, *wing1, *wing2, *far))
    f = assoc_for(inspect(api, [circle(200, 300, 25), fused], [text("Ø12", 266, 303)]), "Ø12")
    assert f.status.value == "verified"


def test_geometry_fused_into_one_path_is_read_the_same(api: TestClient) -> None:
    c = circle(200, 300, 25)
    shapes, runs = leader_to(200, 300, 25, 0, "Ø12")
    fused = Shape("fused", (), (tuple(c.coords[:0]),))  # placeholder replaced below
    del fused
    pts = [
        (200 + 25 * math.cos(math.radians(a)), 300 + 25 * math.sin(math.radians(a)))
        for a in range(0, 360, 10)
    ]
    ring = tuple(v for p in [*pts, pts[0]] for v in p)
    fused = Shape("fused", (), (ring, (265.0, 300.0, 225.0, 300.0)))
    f = assoc_for(inspect(api, [fused, shapes[1]], runs), "Ø12")
    assert f.status.value == "verified"


def test_a_title_block_symbol_is_never_a_feature_of_a_dimension(api: TestClient) -> None:
    symbol = [circle(520, 780, 7), circle(520, 780, 3.5)]  # a projection-symbol look-alike
    shapes, runs = leader_to(200, 300, 25, 0, "Ø12")
    f = assoc_for(inspect(api, [*symbol, circle(200, 300, 25), *shapes], runs), "Ø12")
    assert f.status.value == "verified" and abs(f.feature[0].coords[0] - 200) < 0.1
    # And a dimension text next to the symbol, with no leader, stays unresolved.
    g = assoc_for(inspect(api, symbol, [text("Ø12", 530, 783)]), "Ø12")
    assert g.status.value == "unresolved" and not g.feature


def test_two_views_are_kept_apart(api: TestClient) -> None:
    left = circle(120, 300, 20)
    right = circle(420, 300, 20)
    s1, t1 = leader_to(120, 300, 20, -90, "Ø10", length=50)
    s2, t2 = leader_to(420, 300, 20, -90, "Ø16", length=50)
    r = inspect(api, [left, right, *s1, *s2], [*t1, *t2])
    a, b = assoc_for(r, "Ø10"), assoc_for(r, "Ø16")
    assert a.status.value == b.status.value == "verified"
    assert abs(a.feature[0].coords[0] - 120) < 0.1 and abs(b.feature[0].coords[0] - 420) < 0.1
    assert a.feature_id != b.feature_id


